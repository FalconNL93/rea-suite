"""The interface census (docs/census.md): rea-census/1 documents, the slot tables, and the diff.

  rea-suite census diff <answers.json> <census.json>... [--json] [--all]
      what the game calls (static and runtime censuses) that the answers leave missing or
      stubbed, by interface; --all lists the answered methods too
  rea-suite census from-frida <log.jsonl> --exe <Game.exe> [--out FILE]
      a runtime census (imports) from `rea-suite frida observer.js` with an "imports" config, on
      Windows: what a run of the original reached

A document is checked on reading: its schema, its kind, and the keys the diff joins on. The slot
tables (`data/census/*.json`, generated by census_slots.py) name each interface's methods and say
which return or hand out another interface; `Slots` is what a static census back end reads them
through. The static census itself is behind `static_census()`, so a second back end (a
decompiler's dataflow) can be added beside the Capstone one in pecensus.py.
"""

from __future__ import annotations

import argparse
import fnmatch
import json
import sys
from dataclasses import dataclass
from pathlib import Path

SCHEMA = "rea-census/1"
KINDS = ("static", "runtime", "answers")
ANSWERS = ("implemented", "stub", "missing")
TABLES = Path(__file__).resolve().parent / "data" / "census"


class CensusError(ValueError):
    pass


# --- slot tables --------------------------------------------------------------------------


@dataclass(frozen=True)
class Method:
    interface: str
    slot: int
    name: str
    args: int
    returns: str | None  # the interface it returns in EAX
    out: tuple[tuple[int, str], ...]  # (stack argument index, interface) it writes
    riid: tuple[int, int] | None  # (IID argument, out-pointer argument) of a QueryInterface
    pops: int  # bytes the callee pops: stdcall and thiscall alike pop their stack arguments
    callbacks: tuple[tuple[int, int, int], ...] = ()  # (function arg, context arg, its parameter)
    returns_float: bool = False


@dataclass(frozen=True)
class Function:
    name: str
    module: str  # a glob, as d3dx9_*.dll
    args: int
    returns: str | None
    out: tuple[tuple[int, str], ...]
    riid: tuple[int, int] | None
    callbacks: tuple[tuple[int, int, int], ...] = ()


def callbacks(row: dict) -> tuple[tuple[int, int, int], ...]:
    return tuple((c["function"], c["context"], c["param"]) for c in row.get("callbacks", []))


class Slots:
    """Every slot table, joined: interfaces by name, factory functions, IIDs by their bytes."""

    def __init__(self, tables: list[dict]):
        self.methods: dict[str, list[Method]] = {}
        self.sdk: dict[str, str] = {}
        self.bases: dict[str, str | None] = {}
        self.thiscall: dict[str, bool] = {}
        self.functions: dict[str, Function] = {}
        self.iids: dict[bytes, str] = {}
        for table in tables:
            if table.get("kind") == "imports":
                continue  # win32-imports.json: winrt's census mode reads it, not the static census
            thiscall = table.get("conv") == "thiscall"
            for name, body in table["interfaces"].items():
                if name in self.methods:
                    continue
                self.sdk[name] = table["sdk"]
                self.bases[name] = body.get("base")
                self.thiscall[name] = thiscall
                self.methods[name] = [
                    Method(
                        name, slot, m["name"], m["args"], m.get("returns"),
                        tuple((o["stack"], o["interface"]) for o in m.get("out", [])),
                        (m["riid"]["iid"], m["riid"]["out"]) if "riid" in m else None,
                        4 * (m["args"] + (0 if thiscall else 1)),
                        callbacks(m),
                        bool(m.get("returns_float")),
                    )
                    for slot, m in enumerate(body["methods"])
                ]  # fmt: skip
            for name, f in table.get("functions", {}).items():
                self.functions.setdefault(
                    name.lower(),
                    Function(
                        name, f["module"], f["args"], f.get("returns"),
                        tuple((o["stack"], o["interface"]) for o in f.get("out", [])),
                        (f["riid"]["iid"], f["riid"]["out"]) if "riid" in f else None,
                        callbacks(f),
                    ),
                )  # fmt: skip
            for name, guid in table.get("iids", {}).items():
                self.iids[bytes.fromhex(guid)] = name

    @classmethod
    def load(cls, directory: Path = TABLES) -> Slots:
        return cls(
            [json.loads(p.read_text(encoding="utf-8")) for p in sorted(directory.glob("*.json"))]
        )

    def method(self, interface: str, slot: int) -> Method | None:
        methods = self.methods.get(interface, [])
        return methods[slot] if 0 <= slot < len(methods) else None

    def function(self, module: str, name: str) -> Function | None:
        f = self.functions.get(name.lower())
        return f if f and fnmatch.fnmatch(module.lower(), f.module) else None

    def is_base(self, base: str, of: str) -> bool:
        """base is of itself or one of its bases."""
        seen = 0
        while of and seen < 32:
            if of == base:
                return True
            of = self.bases.get(of)
            seen += 1
        return False


# --- documents ----------------------------------------------------------------------------


def import_key(row: dict) -> tuple[str, str]:
    return row["module"].lower(), str(row["name"])


def check(doc: dict, where: str = "census") -> dict:
    """The document, checked for what the diff relies on; CensusError otherwise."""
    if not isinstance(doc, dict) or doc.get("schema") != SCHEMA:
        raise CensusError(
            f"{where}: not a {SCHEMA} document (schema {doc.get('schema') if isinstance(doc, dict) else None!r})"
        )
    if doc.get("kind") not in KINDS:
        raise CensusError(f"{where}: kind {doc.get('kind')!r} is none of {', '.join(KINDS)}")
    for i in doc.get("interfaces", []):
        if not isinstance(i.get("name"), str) or not isinstance(i.get("methods"), list):
            raise CensusError(f"{where}: an interface without a name or methods")
        for m in i["methods"]:
            if not isinstance(m.get("slot"), int) or m["slot"] < 0:
                raise CensusError(f"{where}: {i['name']} has a method without a slot")
            if "answer" in m and m["answer"] not in ANSWERS:
                raise CensusError(f"{where}: {i['name']} slot {m['slot']}: answer {m['answer']!r}")
    for row in doc.get("imports", []):
        if not isinstance(row.get("module"), str) or not isinstance(row.get("name"), str):
            raise CensusError(f"{where}: an import without a module or name")
    return doc


def read(path: Path) -> dict:
    try:
        doc = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as e:
        raise CensusError(f"{path}: {e}") from e
    return check(doc, str(path))


# --- diff ---------------------------------------------------------------------------------


@dataclass
class Gap:
    interface: str  # empty for an import
    slot: int | None
    module: str
    name: str
    answer: str  # implemented, stub or missing (missing: no thunk, or a thunk without a host)
    static_sites: int = 0
    runtime_calls: int = 0
    sdk: str | None = None
    guest: bool = False  # an import the game's own DLL answers

    def as_json(self) -> dict:
        row = {
            "answer": self.answer,
            "static_sites": self.static_sites,
            "runtime_calls": self.runtime_calls,
        }
        if self.interface:
            return {"interface": self.interface, "slot": self.slot, "name": self.name, **row}
        return {
            "module": self.module,
            "name": self.name,
            **row,
            **({"guest": True} if self.guest else {}),
        }


def diff(answers: dict, censuses: list[dict]) -> tuple[list[Gap], list[str]]:
    """Every method and import the censuses list, with the answers' word on it, and warnings
    (an interface whose sdk differs between the sides)."""
    if answers.get("kind") != "answers":
        raise CensusError(f"the first document is kind {answers.get('kind')!r}, not answers")
    said: dict[tuple, str] = {}
    sdks: dict[str, str] = {}
    for i in answers.get("interfaces", []):
        if i.get("sdk"):
            sdks[i["name"]] = i["sdk"]
        for m in i["methods"]:
            said[(i["name"], m["slot"])] = m.get("answer", "implemented")
    for row in answers.get("imports", []):
        said[import_key(row)] = row.get("answer", "implemented")
    # a DLL the game ships and the runtime loads as guest code answers its own imports
    guest = {
        str(image.get("name", "")).lower()
        for doc in censuses
        if doc.get("kind") == "runtime"
        for image in doc.get("source", {}).get("images", [])
        if str(image.get("name", "")).lower().endswith(".dll")
    }
    gaps: dict[tuple, Gap] = {}
    warnings: list[str] = []
    for doc in censuses:
        if doc.get("kind") == "answers":
            raise CensusError("only one answers document is joined")
        runtime = doc["kind"] == "runtime"
        for i in doc.get("interfaces", []):
            name = i["name"]
            if i.get("sdk") and name in sdks and sdks[name] != i["sdk"]:
                warnings.append(
                    f"{name}: {doc['kind']} census reads it as {i['sdk']}, the answers as {sdks[name]}"
                )
            for m in i["methods"]:
                key = (name, m["slot"])
                gap = gaps.setdefault(
                    key,
                    Gap(
                        name,
                        m["slot"],
                        "",
                        m.get("name") or f"slot {m['slot']}",
                        said.get(key, "missing"),
                        sdk=i.get("sdk"),
                    ),
                )
                if m.get("name") and gap.name.startswith("slot "):
                    gap.name = m["name"]
                count(gap, m.get("sites", []), runtime)
        for row in doc.get("imports", []):
            key = import_key(row)
            answer = said.get(key, "implemented" if key[0] in guest else "missing")
            gap = gaps.setdefault(key, Gap("", None, key[0], key[1], answer, guest=key[0] in guest))
            count(gap, row.get("sites", []), runtime)
    order = {"missing": 0, "stub": 1, "implemented": 2}
    rows = sorted(
        gaps.values(),
        key=lambda g: (
            g.interface == "",
            g.interface or g.module,
            order[g.answer],
            g.slot or 0,
            g.name,
        ),
    )
    return rows, warnings


def count(gap: Gap, sites: list[dict], runtime: bool) -> None:
    if runtime:
        gap.runtime_calls += sum(int(s.get("count", 1)) for s in sites)
    else:
        gap.static_sites += len(sites)


def static_coverage(censuses: list[dict]) -> dict | None:
    """How much of what a run reached the static census found: the runtime's interface calls
    made from the game's executable, joined with the static sites by return address. None
    without both kinds."""
    static = [d for d in censuses if d["kind"] == "static"]
    runtime = [d for d in censuses if d["kind"] == "runtime"]
    if not static or not runtime:
        return None
    found: dict[int, tuple[str, int]] = {}
    for doc in static:
        for i in doc.get("interfaces", []):
            for m in i["methods"]:
                for site in m.get("sites", []):
                    if site.get("return"):
                        found[int(site["return"], 16)] = (i["name"], m["slot"])
    exe = {str(d.get("source", {}).get("name") or "").lower() for d in static}
    reached = matched = 0
    wrong, missed = [], []
    for doc in runtime:
        for i in doc.get("interfaces", []):
            for m in i["methods"]:
                for site in m.get("sites", []):
                    image = str(site.get("image") or "").lower()
                    if (image and image not in exe) or not site.get("return"):
                        continue  # a call from a DLL the game ships: not in the executable
                    reached += 1
                    at = int(site["return"], 16)
                    row = {
                        "interface": i["name"],
                        "slot": m["slot"],
                        "name": m.get("name"),
                        "return": site["return"],
                    }
                    if found.get(at) == (i["name"], m["slot"]):
                        matched += 1
                    elif at in found:
                        wrong.append({**row, "static": f"{found[at][0]} slot {found[at][1]}"})
                    else:
                        missed.append(row)
    return {"reached": reached, "found": matched, "wrong": wrong, "missed": missed}


def imports_table(directory: Path = TABLES) -> dict[str, dict]:
    """win32-imports.json's functions (module!Name), or none when it is absent."""
    path = directory / "win32-imports.json"
    return json.loads(path.read_text(encoding="utf-8"))["functions"] if path.exists() else {}


def check_counts(answers: dict, slots: Slots, imports: dict[str, dict]) -> list[str]:
    """The answers' argument counts and float returns that differ from the SDK's (the slot
    tables, win32-imports.json): a runtime that returns from a missing method or import by a
    wrong count pops the wrong number of bytes. Only entries that carry `args` are checked."""
    found = []
    for i in answers.get("interfaces", []):
        for m in i["methods"]:
            ref = slots.method(i["name"], m["slot"])
            if "args" not in m or ref is None:
                continue
            where = f"{i['name']}::{ref.name} (slot {m['slot']})"
            if m["args"] != ref.args:
                found.append(
                    f"{where}: the runtime says {m['args']} arguments, {slots.sdk[i['name']]} says {ref.args}"
                )
            if bool(m.get("returns_float")) != ref.returns_float:
                found.append(f"{where}: the runtime says it returns {'a float' if m.get('returns_float') else 'no float'}, "
                             f"{slots.sdk[i['name']]} says {'a float' if ref.returns_float else 'no float'}")  # fmt: skip
    for row in answers.get("imports", []):
        key = f"{row['module'].lower()}!{row['name']}"
        ref = imports.get(key)
        if "args" not in row or ref is None or ref.get("args") is None:
            continue
        if row["args"] != ref["args"]:
            found.append(
                f"{key}: the runtime says {row['args']} arguments, the import table {ref['args']} ({ref['conv']})"
            )
    return found


def diff_text(rows: list[Gap], warnings: list[str], every: bool) -> list[str]:
    lines = [f"warning: {w}" for w in warnings]
    shown = [g for g in rows if every or g.answer != "implemented"]
    group = None
    for g in shown:
        head = g.interface or g.module
        if head != group:
            group = head
            total = [r for r in rows if (r.interface or r.module) == head]
            open_ = sum(1 for r in total if r.answer != "implemented")
            lines.append(f"{head}: {open_} of {len(total)} called not answered")
        where = f"slot {g.slot:3d} " if g.interface else ""
        seen = []
        if g.static_sites:
            seen.append(f"{g.static_sites} sites")
        if g.runtime_calls:
            seen.append(f"{g.runtime_calls} calls in the run")
        if g.guest:
            seen.append("the game's own DLL")
        lines.append(f"  {where}{g.name:32s} {g.answer:11s} {', '.join(seen)}")
    missing = sum(1 for g in rows if g.answer != "implemented")
    lines.append(f"{missing} of {len(rows)} methods and imports the game calls are not answered")
    return lines


# --- the static census --------------------------------------------------------------------


def static_census(
    image, functions=None, slots: Slots | None = None, backend: str = "capstone", **options
) -> dict:
    """The static census of an image, as a rea-census/1 document. One back end today."""
    if backend != "capstone":
        raise CensusError(f"no static census back end {backend!r} (capstone)")
    from rea_suite import pecensus

    return pecensus.census(image, slots or Slots.load(), functions=functions, **options)


# --- runtime censuses from other tools --------------------------------------------------------


def from_frida(lines: list[str], exe_name: str, image_base: int) -> dict:
    """A rea-census/1 runtime document (imports only) from an observer.js log: the last
    `imports` report's counts per caller, the first caller of each import marked. Callers are
    offsets into the module, made VAs at the executable's preferred base so they join the
    static census's return addresses."""
    first: dict[str, str] = {}
    last: dict | None = None
    for line in lines:
        try:
            record = json.loads(line)
        except json.JSONDecodeError:
            continue
        if record.get("kind") == "import" and record.get("import") not in first:
            first[record["import"]] = str(record.get("caller", "")).rpartition("+")[2]
        elif record.get("kind") == "imports":
            last = record
    if last is None:
        raise CensusError(
            "the log has no imports report (observer.js with an imports config, and --seconds or an interval)"
        )
    imports = []
    for key, row in sorted(last.get("counts", {}).items()):
        module, _, name = key.partition("!")
        sites = []
        for offset, count in sorted(row.get("callers", {}).items(), key=lambda kv: int(kv[0], 16)):
            site = {
                "return": f"{image_base + int(offset, 16):#x}",
                "count": count,
                "image": exe_name,
            }
            if first.get(key) == offset:
                site["first"] = True
            sites.append(site)
        imports.append(
            {
                "module": module.lower(),
                "name": name,
                "answer": "implemented",
                "calls": row.get("calls", 0),
                "sites": sites,
            }
        )
    return {
        "schema": SCHEMA,
        "kind": "runtime",
        "source": {
            "name": exe_name,
            "image_base": f"{image_base:#x}",
            "images": [{"name": exe_name, "base": f"{image_base:#x}"}],
        },
        "producer": {"name": "rea-suite frida observer.js", "module": last.get("module")},
        "interfaces": [],
        "imports": imports,
    }


# --- command line -------------------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(
        prog="rea-suite census", description="The interface census (docs/census.md)."
    )
    p.add_argument("--caller-cwd", type=Path, default=Path.cwd(), help=argparse.SUPPRESS)
    sub = p.add_subparsers(dest="command", required=True)
    d = sub.add_parser("diff", help="what the game calls that the answers leave missing or stubbed")
    d.add_argument("answers", type=Path, help="the runtime's answers (kind answers)")
    d.add_argument("censuses", type=Path, nargs="+", help="static and runtime censuses of the game")
    d.add_argument("--all", action="store_true", help="list the answered methods and imports too")
    d.add_argument("--json", action="store_true")
    f = sub.add_parser("from-frida", help="a runtime census from an observer.js imports log")
    f.add_argument("log", type=Path, help="the JSON lines `rea-suite frida --log` wrote")
    f.add_argument("--exe", type=Path, required=True, help="the executable the run observed")
    f.add_argument("--out", type=Path, help="write the document here instead of stdout")
    args = p.parse_args(argv)
    if args.command == "from-frida":
        return cmd_from_frida(args)
    try:
        answers = read(args.caller_cwd / args.answers)
        docs = [read(args.caller_cwd / c) for c in args.censuses]
        rows, warnings = diff(answers, docs)
        counts = check_counts(answers, Slots.load(), imports_table())
        coverage = static_coverage(docs)
    except CensusError as e:
        print(f"census: {e}", file=sys.stderr)
        return 2
    if args.json:
        shown = [g.as_json() for g in rows if args.all or g.answer != "implemented"]
        print(
            json.dumps(
                {
                    "warnings": warnings,
                    "rows": shown,
                    "static_coverage": coverage,
                    "count_mismatches": counts,
                },
                indent=1,
            )
        )
        return 0
    print("\n".join(diff_text(rows, warnings, args.all)))
    if coverage:
        print(
            f"static census: {coverage['found']} of the run's {coverage['reached']} interface calls "
            f"from the executable found, {len(coverage['wrong'])} on another interface, "
            f"{len(coverage['missed'])} missed"
        )
        for row in coverage["wrong"]:
            print(
                f"  wrong  {row['return']}  {row['interface']} slot {row['slot']}, static says {row['static']}"
            )
    if counts:
        print(f"{len(counts)} argument counts or float returns differ from the SDK's:")
        for line in counts:
            print(f"  {line}")
    return 0


def cmd_from_frida(args) -> int:
    from rea_suite.pemodel import Image

    try:
        image = Image.open(args.caller_cwd / args.exe)
        lines = (args.caller_cwd / args.log).read_text(encoding="utf-8").splitlines()
        doc = from_frida(lines, args.exe.name, image.base)
    except (OSError, ValueError, CensusError) as e:
        print(f"census: {e}", file=sys.stderr)
        return 2
    text = json.dumps(doc, indent=1) + "\n"
    if args.out:
        (args.caller_cwd / args.out).write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    print(f"{len(doc['imports'])} imports reached", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
